// Работа с телефонами.
//
// Номера редактируются в админке, то есть формат ввода не контролируется:
// «8 925 888-37-00», «+7 (925) 888-37-00», «7 925 8883700» — всё это один и
// тот же номер. Поэтому разбор здесь терпимый к любому оформлению, а места
// вывода не должны сами резать строку регулярками.

/** Ссылка для звонка. Оставляем цифры и ведущий «+», как их ввёл администратор. */
export function telHref(phone: string): string {
  return `tel:${phone.replace(/[^\d+]/g, "")}`;
}

/**
 * Номер в формате E.164 для структурированных данных (JSON-LD).
 *
 * Наивный вариант («+7» + цифры без ведущей восьмёрки) ломался на номере,
 * введённом как «+7 925 …»: ведущей восьмёрки там нет, зато семёрка уже есть,
 * и на выходе получалось «+779258883700». Здесь код страны определяется по
 * длине и первой цифре, а не по одному частному случаю.
 *
 * @returns пустую строку, если цифр в номере нет вовсе.
 */
export function toE164(phone: string): string {
  const raw = phone.trim();
  const explicitCountryCode = raw.startsWith("+");
  let digits = raw.replace(/\D/g, "");

  if (!digits) return "";

  if (digits.length === 11 && (digits[0] === "8" || digits[0] === "7")) {
    // Российская запись: «8 9xx…» и «7 9xx…» — один номер, код страны 7.
    digits = `7${digits.slice(1)}`;
  } else if (!explicitCountryCode && digits.length === 10) {
    // Номер без кода страны — считаем российским.
    digits = `7${digits}`;
  }

  return `+${digits}`;
}

/**
 * Ссылка на чат в Telegram из значения контакта.
 *
 * Поле «Telegram» правится в админке и содержит там номер телефона
 * («8 966 979-55-66»), но администратор вправе вписать и юзернейм («@mayak»),
 * и готовую ссылку. Поэтому ссылка ВСЕГДА собирается из значения контакта, а
 * не пишется в вёрстке константой: иначе правка номера меняла бы подпись, но
 * не адрес.
 *
 * По номеру Telegram открывает чат по адресу `t.me/+<E.164>` — тот же формат,
 * что и в JSON-LD.
 *
 * @returns null, если из значения нельзя собрать рабочий адрес. Место вывода
 *   в этом случае обязано не рисовать ссылку, а не вести на `https://t.me/`.
 */
export function telegramHref(value: string): string | null {
  const raw = value.trim();
  if (!raw) return null;

  if (/^https?:\/\//i.test(raw)) return raw;
  if (/^(?:t|telegram)\.me\//i.test(raw)) return `https://${raw}`;

  // Юзернейм: латиница, цифры и подчёркивания, 5–32 символа, начинается с буквы.
  const username = raw.replace(/^@/, "");
  if (/^[a-zA-Z][a-zA-Z0-9_]{4,31}$/.test(username)) return `https://t.me/${username}`;

  const phone = toE164(raw);
  return phone ? `https://t.me/${phone}` : null;
}
