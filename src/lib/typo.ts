// Русская микротипографика для аккуратных переносов (особенно на мобильных).
//
// Функция расставляет неразрывные пробелы ( ), чтобы:
//  1. Не оставлять предлоги, союзы и короткие местоимения в конце строки.
//  2. Держать вместе смысловые связки («до 300 км», «под задачу», «с учётом» и т. д.).
//  3. Не оставлять тире в конце строки (склеиваем тире с соседними словами).
//
// ВАЖНО: применять только к ОТОБРАЖАЕМОМУ тексту при рендере, а не к значениям,
// которые участвуют в логике (сравнения, ключи состояния). Ручные переносы «\n»
// (используются вместе с whitespace-pre-line) сохраняются как жёсткие переносы —
// функция работает только с обычными пробелами.

const NBSP = " ";

// Явные смысловые связки из ТЗ — склеиваем целиком.
// Регистр совпадения сохраняем: заменяем только пробелы внутри на неразрывные
// (поэтому «До 300 км» в начале предложения не превращается в «до 300 км»).
const PHRASES: RegExp[] = [
  /до 300 км/gi,
  /по всей России/gi,
  /в Раменском городском округе/gi,
  /по задаче/gi,
  /под задачу/gi,
  /на объект/gi,
  /в комплекте/gi,
  /с учётом/gi,
  /по запросу/gi,
  /из чего/gi,
  /и почему/gi,
];

// Тире с обычными пробелами по обеим сторонам: перед тире оставляем обычный
// (переносимый) пробел, после тире ставим неразрывный. Так тире не оказывается
// в конце строки (правило ТЗ), а длинная фраза «слово — фраза» при нехватке
// места переносится по пробелу перед тире и не создаёт слишком широкий токен.
const DASH_RE = / ([—–]) /g;

// Число + короткая единица измерения («300 км», «100 %», «12 м²»).
// В JS «\b» работает только с ASCII, поэтому конец единицы проверяем
// негативным lookahead на букву.
const NUM_UNIT_RE =
  /(\d) (?=(?:км|мм|см|кг|м²|м³|мин|м|т|ч|шт|л|руб|₽|%|°C)(?![А-Яа-яЁёA-Za-z]))/gu;

// Короткие служебные слова (предлоги, союзы, местоимения) + любые 1–2-буквенные
// слова — склеиваем со следующим словом, чтобы они не висли в конце строки.
// Граница слева (lookbehind) и следующий значимый символ справа (lookahead)
// не потребляются, поэтому цепочки коротких слов обрабатываются подряд.
const SHORT_RE =
  /(?<=^|[\s(«"„' —–])((?:[А-Яа-яЁё]{1,2})|для|под|над|при|про|без|что|как|так|или|чем|это|его|её|ему|там|где) (?=[«"„(0-9А-Яа-яЁё])/giu;

/** Расставляет неразрывные пробелы в русском тексте для аккуратных переносов. */
export function typo(input: string): string {
  if (!input) return input;
  let s = input;

  for (const re of PHRASES) s = s.replace(re, (m) => m.split(" ").join(NBSP));
  s = s.replace(DASH_RE, ` $1${NBSP}`);
  s = s.replace(NUM_UNIT_RE, `$1${NBSP}`);
  s = s.replace(SHORT_RE, `$1${NBSP}`);

  return s;
}
