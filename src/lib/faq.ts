/**
 * Разметка FAQPage. Ставится только на /faq: страница с вопросами одна, и
 * второй такой же объект на главной был бы дублем сущности.
 *
 * Вопросы принимаются аргументом, а не берутся из константы: на сайте они
 * приходят из базы, и снятый с публикации вопрос не должен остаться в разметке.
 */
export function buildFaqJsonLd(url: string, items: FaqItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "@id": `${url}#faqpage`,
    url,
    inLanguage: "ru-RU",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };
}
